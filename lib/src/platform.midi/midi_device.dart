import 'midi_port.dart';

//////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////
class MidiDevice {
  String name;
  String id;
  String type;
  List<MidiPort> inputPorts = [];
  List<MidiPort> outputPorts = [];
  bool connected;
  MidiDevice(this.id, this.name, this.type, this.connected);
  Map<String, Object> get toDictionary {
    return {"name": name, "id": id, "type": type, "connected": connected};
  }

  @override
  bool operator ==(Object other) => other is MidiDevice && id == other.id;
  @override
  int get hashCode => id.hashCode;
}
