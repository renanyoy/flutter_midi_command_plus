class MidiPort {
  final String deviceId;
  final int port;
  const MidiPort({required this.deviceId, required this.port});
  @override
  bool operator ==(covariant MidiPort other) {
    if (identical(this, other)) return true;
    return other.deviceId == deviceId && other.port == port;
  }

  @override
  int get hashCode => deviceId.hashCode ^ port.hashCode;
}
